// Prints the pricing / allowance / margin evidence tables as Markdown
// (internal analysis; changes no price, activates no allowance).
// Run with: node scripts/pricing-scenarios.js [--out=docs/finance/PRICING_AND_ALLOWANCE_EVIDENCE.md]
'use strict';

const fs = require('fs');
const path = require('path');
const ps = require('../services/finance/pricingScenarios');

const quotes = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'docs', 'finance', 'carrier-quotes.json'), 'utf8'));
const twilio = quotes.carriers[0];
const PRICES = [4.99, 5.99, 6.99, 7.99, 9.99];
const CHANNELS = ['store15', 'stripe'];
const CH_LABEL = { store15: 'Store 15%', stripe: 'Stripe', apple30: 'Apple 30%' };
const ALLOWANCES = [50, 75, 100, 150, 200, 300];
const MARGINS = [0.3, 0.4, 0.5, 0.6];
const STRESSES = [
  { key: 'base', label: 'Twilio confirmed rates', opts: {} },
  { key: 'plus25', label: 'provider + AI rates +25%', opts: { stress: 0.25 } },
  { key: 'appleg', label: 'app leg billed at list ($0.004/min)', opts: { appLegBilled: true } },
];
const gbp = (n) => (n < 0 ? '−' : '') + '£' + Math.abs(n).toFixed(2);
const pct = (n) => (n < 0 ? '−' : '') + Math.abs(Math.round(n * 100)) + '%';
const out = [];
const p = (s = '') => out.push(s);
const table = (head, rows) => { p('| ' + head.join(' | ') + ' |'); p('|' + head.map(() => '---').join('|') + '|'); rows.forEach((r) => p('| ' + r.join(' | ') + ' |')); p(); };

const r0 = ps.rates(twilio);
p('# Pricing, allowance and margin evidence');
p();
p(`Generated by \`node scripts/pricing-scenarios.js\` on ${new Date().toISOString().slice(0, 10)}. **Internal evidence only: no price is chosen, no allowance is activated, and the live £4.99 price is unchanged.** £4.99 is shown only as the reference column.`);
p();
p('**Margin** = contribution ÷ net revenue (price ex-VAT). Contribution = net revenue − payment/store fee − every variable provider and AI cost. Fixed overheads (hosting, staff, marketing) are *not* deducted.');
p();
p('## 1. Unit costs used');
p();
table(['Item', 'Cost', 'Status'], [
  ['UK number', `${gbp(r0.number)}/month`, 'CONFIRMED (Twilio Pricing API + billing)'],
  ['Connected minute (inbound PSTN leg; **trusted calls too**)', `£${r0.connected.toFixed(6)}`, 'CONFIRMED; Twilio Support confirmed the leg is billable for the whole call'],
  ['+ Media Stream per monitored minute', `£${r0.streamPerMin.toFixed(6)}`, 'CONFIRMED'],
  ['+ transcription per monitored minute', `£${r0.transcriptionPerMin.toFixed(6)}`, 'ESTIMATED (OpenAI list × 0.79)'],
  ['= monitored minute', `£${ps.monitoredMinuteCost(r0).toFixed(6)}`, ''],
  ['Greeting per unknown call', gbp(r0.greeting).replace('£0.00', '£0.0006'), 'CONFIRMED'],
  ['SMS segment', `£${r0.smsSegment.toFixed(4)}`, 'CONFIRMED (note: warning SMS currently fail, error 21661)'],
  ['Started-minute rounding', '+0.55 min per call', 'ASSUMPTION'],
  ['App leg', '£0 billed to date (list $0.004/min)', 'Stress scenario below'],
]);

p('## 2. Revenue waterfall per price');
p();
table(['Price inc VAT', 'VAT', 'Net ex-VAT', 'Store fee 15%', 'After store fee', 'Stripe fee', 'After Stripe', 'Apple 30% after fee'], PRICES.map((price) => {
  const s = ps.revenue(price, 'store15'); const st = ps.revenue(price, 'stripe'); const a30 = ps.revenue(price, 'apple30');
  return [gbp(price), gbp(s.vat), gbp(s.net), gbp(s.fee), gbp(s.afterFees), gbp(st.fee), gbp(st.afterFees), gbp(a30.afterFees)];
}));

p('## 3. Usage profiles (ASSUMPTIONS)');
p();
p('There is no real usage distribution yet. These shapes are illustrative, and replacing them with measured data is the first thing to do once real customers exist. "Unknown minutes" beyond the allowance continue **unmonitored** but are still billed inbound.');
p();
table(['Profile', 'Trusted min', 'Unknown min', 'Trusted calls', 'Unknown calls', 'SMS'], Object.values(ps.PROFILES).map((u) => [u.label, u.trusted, u.unknownMinutes, u.trustedCalls, u.unknownCalls, u.sms]));

p('## 4. Contribution and margin by profile, with a 100-minute monitored allowance');
p();
for (const channel of CHANNELS) {
  p(`### ${CH_LABEL[channel]}`);
  p();
  table(['Profile', 'Cost/month', ...PRICES.map((x) => gbp(x))], Object.entries(ps.PROFILES).map(([, u]) => {
    const cells = PRICES.map((price) => {
      const c = ps.contribution(twilio, { priceGbp: price, channel, usage: u, allowanceMinutes: 100 });
      return `${gbp(c.contribution)} (${pct(c.margin)})`;
    });
    return [u.label, gbp(ps.householdCost(twilio, u, 100).total), ...cells];
  }));
}

p('## 5. Margin when a household uses its whole monitored allowance');
p();
p('This is the worst case for monitored cost. Each cell is the margin at that price; rows are allowance × trusted minutes. Store 15% channel, confirmed rates.');
p();
for (const trusted of [0, 150, 400, 800]) {
  p(`### ${trusted} trusted minutes/month`);
  p();
  table(['Allowance (fully used)', 'Cost', ...PRICES.map((x) => gbp(x))], ALLOWANCES.map((A) => {
    const usage = { trusted, unknownMinutes: A, trustedCalls: Math.round(trusted / 4), unknownCalls: Math.round(A / 4), sms: 1 };
    return [`${A} min`, gbp(ps.householdCost(twilio, usage, A).total), ...PRICES.map((price) => pct(ps.contribution(twilio, { priceGbp: price, channel: 'store15', usage, allowanceMinutes: A }).margin))];
  }));
}

p('## 6. Largest fully-used allowance that keeps a target margin');
p();
p('Minutes of monitored allowance, assuming the household uses all of it. A negative or "—" value means no allowance reaches the target at that price, because the number rental plus trusted minutes already use up the budget.');
p();
for (const st of STRESSES) {
  for (const channel of CHANNELS) {
    p(`### ${CH_LABEL[channel]}, ${st.label}`);
    p();
    const rows = [];
    for (const trusted of [0, 150, 400]) {
      for (const m of MARGINS) {
        rows.push([`${trusted} trusted min, ${pct(m)} margin`, ...PRICES.map((price) => {
          const v = ps.maxAllowanceForMargin(twilio, { priceGbp: price, channel, targetMargin: m, trusted, ...st.opts });
          return v > 0 ? `${v}` : '—';
        })]);
      }
    }
    table(['Trusted use / target', ...PRICES.map((x) => gbp(x))], rows);
  }
}

p('## 7. When trusted-call usage alone destroys the margin');
p();
p('Trusted minutes per month at which margin falls to the target, **with no monitored use at all** (A = 0) and with a 100-minute allowance fully used. Store 15% channel. Trusted calls are billed on the inbound leg for their whole duration.');
p();
for (const st of STRESSES) {
  p(`### ${st.label}`);
  p();
  const rows = [];
  for (const A of [0, 100]) {
    for (const m of [0, ...MARGINS]) {
      rows.push([`allowance ${A} used, margin ${m === 0 ? 'break-even' : pct(m)}`, ...PRICES.map((price) => {
        const t = ps.trustedMinutesAtMargin(twilio, { priceGbp: price, channel: 'store15', targetMargin: m, allowanceMinutes: A, ...st.opts });
        return t > 0 ? `${t} (${(t / 30).toFixed(0)}/day)` : '—';
      })]);
    }
  }
  table(['Case', ...PRICES.map((x) => gbp(x))], rows);
}

p('## 8. Per-household cost thresholds implied by a target margin');
p();
p('These feed the Layer B WATCH and ALERT thresholds. WATCH = the monthly cost above which that household is under the target margin. ALERT = the cost above which it is loss-making.');
p();
table(['Price', 'Channel', 'After-fees revenue', 'WATCH at 40% margin', 'WATCH at 30%', 'ALERT (loss)'], PRICES.flatMap((price) => CHANNELS.map((channel) => {
  const t40 = ps.householdCostThresholds({ priceGbp: price, channel, targetMargin: 0.4 });
  const t30 = ps.householdCostThresholds({ priceGbp: price, channel, targetMargin: 0.3 });
  return [gbp(price), CH_LABEL[channel], gbp(t40.afterFees), gbp(t40.watchAtCostGbp), gbp(t30.watchAtCostGbp), gbp(t40.lossAtCostGbp)];
})));

const arg = process.argv.find((a) => a.startsWith('--out='));
if (arg) {
  fs.writeFileSync(arg.slice(6), out.join('\n'));
  console.log(`written ${arg.slice(6)}`);
} else {
  console.log(out.join('\n'));
}
